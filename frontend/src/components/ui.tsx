import clsx from 'clsx';
import Link from 'next/link';
import type { ComponentProps, ReactNode } from 'react';
import type { Provenance, TwinHealth } from '@promesa/contracts';
import { HEALTH_LABEL, HEALTH_SYMBOL, HEALTH_TONE, type Tone } from '@/lib/format';

type Variant = 'primary' | 'secondary' | 'ghost' | 'danger';
type Size = 'sm' | 'md' | 'lg';

const base =
  'inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-[var(--radius-control)] font-medium transition-[background-color,border-color,color,transform] duration-[var(--dur-fast)] select-none disabled:cursor-not-allowed disabled:opacity-50 active:translate-y-px';
const variants: Record<Variant, string> = {
  primary: 'bg-signal text-paper hover:bg-signal-strong border border-signal',
  secondary: 'bg-paper text-ink border border-hairline-strong hover:border-signal',
  ghost: 'text-ink hover:bg-cutout border border-transparent',
  danger: 'bg-breach text-paper border border-breach hover:bg-breach/90',
};
const sizes: Record<Size, string> = {
  sm: 'h-8 px-3 text-[13px]',
  md: 'h-10 px-4 text-sm',
  lg: 'h-12 px-6 text-[15px]',
};

export function buttonClass(variant: Variant = 'primary', size: Size = 'md', extra?: string) {
  return clsx(base, variants[variant], sizes[size], extra);
}

export function Button({
  variant = 'primary',
  size = 'md',
  className,
  busy,
  children,
  ...props
}: ComponentProps<'button'> & { variant?: Variant; size?: Size; busy?: boolean }) {
  return (
    <button
      type="button"
      className={buttonClass(variant, size, className)}
      aria-busy={busy || undefined}
      disabled={props.disabled || busy}
      {...props}
    >
      {busy ? <Spinner /> : null}
      {children}
    </button>
  );
}

export function ButtonLink({
  variant = 'primary',
  size = 'md',
  className,
  ...props
}: ComponentProps<typeof Link> & { variant?: Variant; size?: Size }) {
  return <Link className={buttonClass(variant, size, className)} {...props} />;
}

export function Spinner() {
  return (
    <span
      aria-hidden
      className="inline-block size-3.5 animate-spin rounded-full border-[1.5px] border-current border-r-transparent"
    />
  );
}

export function Kicker({ children, className }: { children: ReactNode; className?: string }) {
  return <p className={clsx('kicker', className)}>{children}</p>;
}

const toneClass: Record<Tone, string> = {
  neutral: 'text-muted border-hairline-strong bg-paper',
  good: 'text-good border-good/40 bg-good-soft',
  caution: 'text-caution border-caution/45 bg-caution-soft',
  breach: 'text-breach border-breach/45 bg-breach-soft',
  signal: 'text-signal border-signal/40 bg-signal-soft',
};

export function Chip({
  tone = 'neutral',
  children,
  className,
  title,
}: {
  tone?: Tone;
  children: ReactNode;
  className?: string;
  title?: string;
}) {
  return (
    <span
      title={title}
      className={clsx(
        'inline-flex items-center gap-1.5 rounded-full border px-2 py-0.5 font-mono text-[11px] uppercase tracking-[0.08em]',
        toneClass[tone],
        className,
      )}
    >
      {children}
    </span>
  );
}

/** Health is a stamp: symbol + words, never colour alone. */
export function HealthStamp({ health, size = 'md' }: { health: TwinHealth; size?: 'md' | 'lg' }) {
  const tone = HEALTH_TONE[health];
  return (
    <span
      className={clsx(
        'inline-flex items-center gap-2 rounded-[5px] border-[1.5px] font-mono uppercase tracking-[0.14em]',
        size === 'lg' ? 'px-3 py-1.5 text-[13px]' : 'px-2 py-0.5 text-[11px]',
        toneClass[tone],
      )}
    >
      <span aria-hidden>{HEALTH_SYMBOL[health]}</span>
      {HEALTH_LABEL[health]}
    </span>
  );
}

export function SimulatedTag({ className }: { className?: string }) {
  return (
    <Chip
      tone="caution"
      className={className}
      title="Generated by the demo scenario. Not a real event."
    >
      Simulated
    </Chip>
  );
}

export function ProvenanceTag({ provenance }: { provenance: Provenance | null }) {
  if (!provenance) return <Chip>Planned · no record</Chip>;
  if (provenance.verification === 'SIMULATED') return <SimulatedTag />;
  const tone: Tone =
    provenance.verification === 'VERIFIED'
      ? 'good'
      : provenance.verification === 'ATTESTED'
        ? 'signal'
        : 'neutral';
  return (
    <Chip tone={tone} title={`Source id ${provenance.sourceId}`}>
      {provenance.source.replace(/_/g, ' ')} · {provenance.verification.toLowerCase()}
    </Chip>
  );
}

export function Sheet({
  className,
  stacked,
  folded,
  as: As = 'section',
  children,
  ...rest
}: {
  className?: string;
  stacked?: boolean;
  folded?: boolean;
  as?: 'section' | 'div' | 'article' | 'aside';
  children: ReactNode;
} & Omit<ComponentProps<'section'>, 'className' | 'children' | 'ref'>) {
  return (
    <As
      className={clsx(
        'sheet',
        stacked && 'sheet-stacked isolate',
        folded && 'sheet-folded',
        className,
      )}
      {...rest}
    >
      {children}
    </As>
  );
}

export function SectionHeading({
  kicker,
  title,
  aside,
  id,
}: {
  kicker?: string;
  title: ReactNode;
  aside?: ReactNode;
  id?: string;
}) {
  return (
    <div className="flex flex-wrap items-end justify-between gap-3">
      <div>
        {kicker ? <Kicker>{kicker}</Kicker> : null}
        <h2 id={id} className="font-display mt-1 text-[22px] leading-tight text-ink">
          {title}
        </h2>
      </div>
      {aside}
    </div>
  );
}

export function StateBlock({
  title,
  children,
  action,
  tone = 'neutral',
}: {
  title: string;
  children?: ReactNode;
  action?: ReactNode;
  tone?: 'neutral' | 'breach';
}) {
  return (
    <div
      role={tone === 'breach' ? 'alert' : 'status'}
      className={clsx(
        'rounded-[var(--radius-sheet)] border border-dashed p-6 text-sm',
        tone === 'breach'
          ? 'border-breach/50 bg-breach-soft text-ink'
          : 'border-hairline-strong text-muted',
      )}
    >
      <p className="font-medium text-ink">{title}</p>
      {children ? <div className="mt-1.5">{children}</div> : null}
      {action ? <div className="mt-4">{action}</div> : null}
    </div>
  );
}

export function Skeleton({ className }: { className?: string }) {
  return <div aria-hidden className={clsx('animate-pulse rounded-md bg-cutout', className)} />;
}

export function LoadingSheet({ label = 'Loading' }: { label?: string }) {
  return (
    <div role="status" aria-live="polite" className="space-y-3">
      <span className="sr-only">{label}…</span>
      <Skeleton className="h-8 w-1/3" />
      <Skeleton className="h-40 w-full" />
      <Skeleton className="h-24 w-2/3" />
    </div>
  );
}

export function Dl({
  items,
  className,
}: {
  items: Array<[string, ReactNode]>;
  className?: string;
}) {
  return (
    <dl
      className={clsx('grid grid-cols-[minmax(7rem,auto)_1fr] gap-x-4 gap-y-2 text-sm', className)}
    >
      {items.map(([k, v]) => (
        <div key={k} className="contents">
          <dt className="text-muted">{k}</dt>
          <dd className="text-ink">{v}</dd>
        </div>
      ))}
    </dl>
  );
}
